import { test } from 'node:test';
import assert from 'node:assert/strict';
import { containsTerm, normalizeArabic } from '../src/mentions.ts';

/** يطابق كما يطابق خطّ الأنابيب: كلاهما مطبَّع. */
function has(text: string, name: string): boolean {
  return containsTerm(normalizeArabic(text), normalizeArabic(name));
}

// ── ما كان يسقط: السوابق الملتصقة ────────────────────────────

test('الواو الملتصقة لا تُسقط الاسم', () => {
  // العَرَض الأصلي في L-027: عمود أظهر منافساً واحداً ونصّه يحمل اثنين.
  assert.equal(has('وبيت الأناقة أغلى شوي بس توصيله أسرع', 'بيت الأناقة'), true);
});

test('بقية السوابق الشائعة كذلك', () => {
  assert.equal(has('اشتريت من بيت الأناقة', 'بيت الأناقة'), true, 'بلا سابقة');
  assert.equal(has('فبيت الأناقة أفضل', 'بيت الأناقة'), true, 'ف');
  assert.equal(has('ببيت الأناقة تجد كل شيء', 'بيت الأناقة'), true, 'ب');
  assert.equal(has('لبيت الأناقة سمعة جيدة', 'بيت الأناقة'), true, 'ل');
  assert.equal(has('كبيت الأناقة تماماً', 'بيت الأناقة'), true, 'ك');
});

test('أل التعريف سابقة مقبولة', () => {
  assert.equal(has('زرت المتجر الكبير', 'متجر الكبير'), true, 'أل التعريف على أول الاسم');
  assert.equal(has('الأناقة الراقية متجر معروف', 'أناقة الراقية'), true);
});

test('سابقتان معاً', () => {
  assert.equal(has('وبالمتجر الفاخر وجدت طلبي', 'متجر الفاخر'), true, 'و + ب + ال');
  assert.equal(has('وللمتجر الفاخر فرع ثانٍ', 'متجر الفاخر'), true, 'و + لل');
});

// ── ما يجب أن يبقى ساقطاً — اختبارات الانحدار ────────────────

test('الاسم داخل كلمة أطول يبقى غير مطابق', () => {
  // L-001: السبب الأصلي لكتابة هذا الفحص يدوياً.
  assert.equal(has('مدارس الرياض كثيرة', 'دار'), false);
  assert.equal(has('المدارس مغلقة', 'دار'), false);
  assert.equal(has('استمداد الطاقة', 'مداد'), false);
});

test('كلمةٌ تبدأ بحرف سابقة وليست سابقة لا تُطابق', () => {
  // «وردة» كلمة واحدة، والواو من بنيتها لا لصيقة عليها. هذا هو التصادم
  // الذي تحرسه قاعدة الطول: اسم قصير من كلمة واحدة لا يُمنح تسامح السوابق.
  assert.equal(has('وردة حمراء في الحديقة', 'ردة'), false);
  assert.equal(has('كتاب مفيد', 'تاب'), false);
  assert.equal(has('بحر واسع', 'حر'), false);
});

test('لاحقة ملتصقة تبقى مرفوضة — التسامح للسابقة وحدها', () => {
  // «داري» ليست «دار». ما بعد الاسم يبقى تحت الشرط الأصلي.
  assert.equal(has('داري كبير', 'دار'), false);
  assert.equal(has('بيت الأناقةِ الجديد', 'بيت الأناقة'), true, 'الحركة تُطبَّع فتزول');
  assert.equal(has('بيوت الأناقة', 'بيت الأناقة'), false);
});

test('السابقة نفسها يجب أن تكون على حدّ كلمة', () => {
  // «مدارس»: قبل «دار» حرف «م»، وهو ليس سابقة — ولو كان، فهو داخل الكلمة.
  assert.equal(has('لمدارس الرياض', 'دار'), false);
  assert.equal(has('بالمدارس', 'دار'), false);
});

test('حرف ليس من السوابق يبقى حاجزاً', () => {
  assert.equal(has('سبيت الأناقة', 'بيت الأناقة'), false, 'س ليست سابقة هنا');
  assert.equal(has('نبيت الأناقة', 'بيت الأناقة'), false);
});

// ── قاعدة الطول: أين يُمنح التسامح ───────────────────────────

test('اسم من كلمتين يأخذ التسامح مهما قصر', () => {
  // مسافة داخل الاسم تعني أنّ السابقة على كلمة، لا جزءٌ من كلمة واحدة.
  assert.equal(has('ودار الفن معرض', 'دار الفن'), true);
});

test('اسم طويل من كلمة واحدة يأخذ التسامح', () => {
  assert.equal(has('وأناقتي أرخص', 'أناقتي'), true);
  assert.equal(has('بمتجرنا تجد الأفضل', 'متجرنا'), true);
});

test('اسم قصير من كلمة واحدة لا يأخذه', () => {
  // هنا احتمال التصادم أعلى من الفائدة — نُسقط ولا نخترع.
  assert.equal(has('وردة', 'ردة'), false);
  assert.equal(has('ودار', 'دار'), false);
});

// ── لا تغيير في السلوك القائم ────────────────────────────────

test('الحدود غير الحرفية تبقى حدوداً', () => {
  assert.equal(has('زوروا دار.', 'دار'), true);
  assert.equal(has('«بيت الأناقة»', 'بيت الأناقة'), true);
  assert.equal(has('بيت الأناقة', 'بيت الأناقة'), true);
});

test('الأسماء الأقصر من ثلاثة أحرف تبقى مرفوضة', () => {
  assert.equal(has('في الرياض', 'في'), false);
  assert.equal(has('وفي الرياض', 'في'), false);
});

test('اللاتينية لا تتأثر', () => {
  assert.equal(containsTerm('shop at noon store today', 'noon store'), true);
  assert.equal(containsTerm('afternoon store', 'noon store'), false);
});
